def readme_block(pr, ar, rb, co) -> str:
    row = _primary_row(pr)
    b = pr["bootstrap"]
    m = ar["metrics"]["euclidean"] if ar else None
    L = ["<!-- results:start (generated by `python -m flypath report`; do not edit) -->", "",
         f"Primary hash size k = {pr['primary_k']} (5% of {pr['projection']['n_cells']} Kenyon cells), "
         f"{pr['n_items']} synthetic mixtures, {pr['B']} curveball nulls:", "",
         "| k | measured | null mean +/- SD | rel. diff. | p (two-sided) | p (Holm) |",
         "|---|---|---|---|---|---|"]
    for r in pr["rows"]:
        holm = "(primary, not adjusted)" if r["primary"] else pval(r["randomization"]["p_two_sided_holm"])
        L.append(f"| {r['k']}{' (primary)' if r['primary'] else ''} | {r['real']:.4f} | "
                 f"{r['null_mean']:.4f} +/- {r['null_sd']:.4f} | {pct(r['relative_difference'], 2)}% | "
                 f"{pval(r['randomization']['p_two_sided'])} | {holm} |")
    equiv = b["equivalent"][f"{b['primary_margin']:.3f}"]
    L += ["", f"Two-stage bootstrap 90% interval for the relative difference at the primary size: "
              f"[{pct(b['relative_ci'][0], 1)}%, {pct(b['relative_ci'][1], 1)}%]; "
              f"equivalence at the pre-specified +/-{100 * b['primary_margin']:.0f}% margin: "
              f"{'yes' if equiv else 'no'}."]
    if m:
        i = m["sizes"].index(pr["primary_k"])
        g = m["gaussian"]
        L += ["", f"Fly hash / Gaussian sign code at k = {pr['primary_k']}: "
                  f"{g['k_bits']['ratio_fly_over'][i]:.2f}x at k bits, "
                  f"{g['storage_matched']['ratio_fly_over'][i]:.2f}x at matched storage "
                  f"({ar['budgets']['storage_matched'][str(pr['primary_k'])]} bits), "
                  f"{g['computation_matched']['ratio_fly_over'][i]:.2f}x at matched operations "
                  f"({ar['budgets']['computation_matched'][str(pr['primary_k'])]} bits)."]
    rp, cb = _load("replication.json"), _load("connectome_benchmarks.json")
    if rp and "mnist" in rp["datasets"]:
        mn = rp["datasets"]["mnist"]
        i4 = rp["protocol"]["hash_lengths"].index(4)
        L += ["", f"2017 protocol with random matrices, MNIST, k = 4: LSH {mn['lsh']['ap']['mean'][i4]:.3f} "
                  f"(reported 0.160), fly hash {mn['fly_10d']['ap']['mean'][i4]:.3f} (reported 0.448)."]
    if cb:
        allr = [r for per in cb["datasets"].values() for r in per["ap"]["rows"]]
        L += ["", f"Connectome under the 2017 protocol (SIFT, GloVe, MNIST via PCA; odours): "
                  f"{pct(min(r['relative_difference'] for r in allr), 1)}% to "
                  f"{pct(max(r['relative_difference'] for r in allr), 1)}% relative to "
                  f"{cb['B']} curveball nulls across {len(allr)} dataset-size combinations."]
    if co:
        L += ["", f"Coverage of the 90% interval in simulation: "
                  f"{100 * co['two_stage']['coverage']:.0f}% (previous procedure: "
                  f"{100 * co['superseded_group_bootstrap']['coverage']:.0f}%)."]
    if rb:
        L += ["", f"Robustness: {len(rb['rows'])} one-factor variations, see "
                  f"[results/SUPPLEMENT.md](results/SUPPLEMENT.md)."]
    L += ["", "<!-- results:end -->"]
    return "\n".join(L)


# ------------------------------------------------------------------ checksums

def verify_checksums(cfg) -> bool:
    from .flyhash import sha256
    ok = True
    for line in (ROOT / "DATA_CHECKSUMS.txt").read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        h, name = line.split(None, 1)
        f = cfg.raw_dir / name
        got = sha256(f) if f.exists() else "missing"
        match = got == h
        ok &= match
        print(f"{'ok  ' if match else 'FAIL'}  {name}")
    return ok


