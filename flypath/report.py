def _plateau(cv: dict, tol_sd: float = 3.0) -> str:
    """First checkpoint from which every chain's co-occurrence statistic stays
    inside `tol_sd` standard deviations of the null distribution (200
    independent draws). Single stationary draws fall outside one SD about a
    third of the time, so a one-SD criterion is never met; three is the
    appropriate envelope for individual values."""
    mu, sd = cv["pool_q_mean"], cv["pool_q_sd"]
    marks = cv["marks"]
    for j, mk in enumerate(marks):
        if all(abs(ch[i]["cooccurrence_q"] - mu) <= tol_sd * sd
               for ch in cv["chains"] for i in range(j, len(marks))):
            return f"{mk:g}"
    return "n/a"


def _jaccard_plateau(cv: dict, tol: float = 0.005) -> tuple[str, float]:
    """First checkpoint from which the mean Jaccard overlap with the measured
    matrix stays within `tol` of its value at the last checkpoint."""
    marks = cv["marks"]
    mean = [np.mean([ch[j]["jaccard_to_real"] for ch in cv["chains"]]) for j in range(len(marks))]
    final = mean[-1]
    for j, mk in enumerate(marks):
        if all(abs(v - final) <= tol for v in mean[j:]):
            return f"{mk:g}", float(final)
    return "n/a", float(final)


